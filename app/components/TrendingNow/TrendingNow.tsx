import React from "react";
import { movies } from "~/data/movies";
import { mockDisplayAds } from "~/data/display-ads";
import { Box, Chip, Grid, Typography } from "@mui/material";
import { formatRuntime, toTitleCase } from "../../utils";
import { PosterWithDetails } from "../PosterWithDetails";

export const TrendingNow = () => {
  const trendingMovies = movies.filter((movie) => movie.vote_average > 7);
  const firstTrendingMovie = trendingMovies[0];
  return (
    <div className="page-container">
      {/* Rubric Item: Advanced HTML5 (<section> element) */}
      <section>
        <h2 className="trending-section-title">Trending Now</h2>
        <div className="trending-now-first-movie">
          {firstTrendingMovie && (
            // Rubric Item: Advanced HTML5 (<iframe> element), Inline HTML CSS Styles
            <iframe
              src={firstTrendingMovie.trailerUrl}
              title={`Trailer for ${firstTrendingMovie.title}`}
              allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
              allowFullScreen
              loading="lazy"
              style={{
                aspectRatio: 16 / 9,
                width: "100%",
                height: "100%",
                border: 0,
                maxWidth: "515px",
              }}
            />
          )}
          <section className="trending-now-first-movie-details">
            <h3>
              {firstTrendingMovie?.title}
              {/* Rubric Item: Character Formatting (small)*/}
              <small> ({firstTrendingMovie?.release_date.getFullYear()})</small>
            </h3>
            <Typography variant="caption" color="textSecondary">
              {firstTrendingMovie?.rating}
              {firstTrendingMovie?.release_date &&
                ` | ${firstTrendingMovie.release_date.toLocaleDateString()}`}
              {firstTrendingMovie?.runtimeMinutes &&
                ` | ${formatRuntime(firstTrendingMovie.runtimeMinutes)}`}
            </Typography>
            <div className="trending-now-genres">
              {firstTrendingMovie?.genres.map((genre) => (
                <Chip
                  key={genre}
                  color="secondary"
                  label={toTitleCase(genre)}
                  size="small"
                />
              ))}
            </div>
            <p>{firstTrendingMovie?.overview}</p>
          </section>
          <figure>
            {/* Rubric Item: Image with alt text*/}
            <img
              src={mockDisplayAds[0].imageUrl}
              alt={mockDisplayAds[0].altText}
            />
            <figcaption>
              {/* Rubric Item: Character Formatting (Bold, Italic), Paragraph Formatting (Link)*/}
              <strong>Figure 1 </strong>
              <em>Frame &amp; Flame queer film festival advertisement</em>
              <p>
                <em>Note.</em> Placeholder image generated by Placehold.co
                (n.d.).{" "}
                <a href={mockDisplayAds[0].imageUrl}>View image source</a>
              </p>
            </figcaption>
          </figure>
        </div>
      </section>
      <Box sx={{ my: "2rem" }}>
        <Grid container spacing={2}>
          {trendingMovies.slice(1, 7).map((movie) => (
            <Grid key={movie.id} size={{ xs: 6, sm: 4, md: 2 }}>
              <PosterWithDetails
                posterUrl={movie.posterUrl}
                title={movie.title}
                releaseDate={movie.release_date}
              />
            </Grid>
          ))}
        </Grid>
      </Box>
    </div>
  );
};
