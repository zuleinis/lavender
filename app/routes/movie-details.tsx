import React from "react";
import { movies, streamingPlatformLinks } from "~/data/movies";
import type { Route } from "./+types/movie-details";
import { mockDisplayAds } from "~/data/display-ads";
import { Chip, Typography } from "@mui/material";
import { formatRuntime, toTitleCase } from "~/utils";

export function loader({ params }: Route.LoaderArgs) {
  const movie = movies.find((item) => item.id === Number(params.movieId));
  if (!movie) throw new Response("Movie not found", { status: 404 });
  return { movie };
}

export default function MovieDetails({ loaderData }: Route.ComponentProps) {
  const { movie } = loaderData;
  return (
    <main>
      <div className="page-container movie-details-container">
        {/* Rubric Item: Image with alt text*/}
        <section>
          <img
            className="movie-details-poster"
            src={movie.posterUrl}
            alt={`Poster for ${movie.title}`}
            loading="lazy"
          />
          <h2>Where to watch</h2>
          {movie.streamingPlatforms?.map((platform) => (
            // Rubric Item: External links
            <div>
              <a
                key={platform}
                href={streamingPlatformLinks[platform]}
                target="_blank"
                rel="noopener noreferrer"
              >
                {platform}
              </a>
              <br />
            </div>
          ))}
        </section>
        <div className="movie-details-content">
          <iframe
            src={movie.trailerUrl}
            title={`Trailer for ${movie.title}`}
            allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
            allowFullScreen
            loading="lazy"
            className="movie-details-trailer"
          />
          <h2>
            {movie.title} <small>{movie.release_date.getFullYear()}</small>
          </h2>
          <Typography variant="caption" color="textSecondary">
            {movie.rating}
            {movie.release_date &&
              ` | ${movie.release_date.toLocaleDateString()}`}
            {movie.runtimeMinutes &&
              ` | ${formatRuntime(movie.runtimeMinutes)}`}
          </Typography>
          <div>
            {movie.genres.map((genre) => (
              <Chip
                key={genre}
                color="secondary"
                label={toTitleCase(genre)}
                size="small"
                className="movie-details-genres"
              />
            ))}
            {movie.categories?.map((category) => (
              <Chip
                key={category}
                color="secondary"
                label={toTitleCase(category)}
                size="small"
                className="movie-details-genres"
              />
            ))}
          </div>
          <div className="movie-description">
            <strong>Overview</strong>
            <p>{movie.overview}</p>
          </div>
          <section>
            <h3>Community reviews</h3>
            {movie.comments?.length ? (
              <ul>
                {movie.comments.map((review, index) => (
                  <li key={index} style={{ margin: ".75rem 0 0 0" }}>
                    {/* Rubric Item: Paragraph Formatting (span, hr)*/}
                    <span>
                      <strong>@{review.username} </strong>
                      <small>{review.timestamp.toLocaleDateString()}</small>
                    </span>
                    <p style={{ margin: ".75rem 0 .75rem 0" }}>{review.body}</p>
                    <hr />
                  </li>
                ))}
              </ul>
            ) : (
              <p>No community reviews yet.</p>
            )}
          </section>
        </div>
        <figure>
          {/* Rubric Item: Image with alt text*/}
          <img
            src={mockDisplayAds[1].imageUrl}
            alt={mockDisplayAds[1].altText}
          />
          <figcaption>
            {/* Rubric Item: Character Formatting (Bold, Italic)*/}
            <strong>Figure 2 </strong>
            <em>Rainbow Picture House advertisement</em>
            <p>
              <em>Note.</em> Placeholder image generated by Placehold.co (n.d.).{" "}
              <a href={mockDisplayAds[1].imageUrl}>View image source</a>
            </p>
          </figcaption>
        </figure>
      </div>
    </main>
  );
}
